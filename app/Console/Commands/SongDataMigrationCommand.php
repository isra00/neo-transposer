<?php

namespace App\Console\Commands;

use App\Support\SongData;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\DB;
use RuntimeException;

class SongDataMigrationCommand extends Command
{
    protected $signature = 'app:song-data-migration {name=song_data : Suffix of the migration file name}';

    protected $description = 'Write the song data edited locally since song_data.sql as a migration, and refresh song_data.sql';

    public function handle(): int
    {
        $file = base_path(SongData::FILE);
        $snapshot = SongData::loadSnapshot('committed', $file);
        try {
            $changes = SongData::changes(SongData::read($snapshot), SongData::read());
        } finally {
            SongData::dropSnapshot($snapshot);
        }

        if (!$changes) {
            $this->info('The local song data is the same as song_data.sql: nothing to migrate.');

            return self::SUCCESS;
        }

        $migration = date('Y_m_d_His') . '_' . $this->argument('name');
        file_put_contents(database_path("migrations/$migration.php"), $this->migrationCode($changes));
        $this->listInCreateTables($migration);
        SongData::export($file);

        // Already in the local DB: recorded as run so `migrate` does not apply it again here.
        DB::table('migrations')->insert(['migration' => $migration, 'batch' => (int) DB::table('migrations')->max('batch') + 1]);

        foreach (array_count_values(array_map(fn ($change) => "{$change[0]} {$change[1]}", $changes)) as $what => $count) {
            $this->line("  $count × $what");
        }
        $this->info("Written database/migrations/$migration.php and refreshed song_data.sql. Review and commit them.");

        return self::SUCCESS;
    }

    /**
     * @param  list<array{'insert'|'update'|'delete', string, string, array<string, mixed>}>  $changes
     */
    private function migrationCode(array $changes): string
    {
        $lines = implode("\n", array_map(fn ($change) => '            ' . $this->export($change) . ',', $changes));

        return <<<PHP
            <?php

            use App\\Support\\SongData;
            use Illuminate\\Database\\Migrations\\Migration;

            /**
             * Song data edited locally, generated by app:song-data-migration. Each change only
             * applies if the database still has the value it is changing.
             */
            return new class() extends Migration
            {
                public function up(): void
                {
                    SongData::migrate([
            $lines
                    ]);
                }
            };

            PHP;
    }

    /**
     * A value as PHP code on one line, so each change reads as one line of the migration.
     */
    private function export(mixed $value): string
    {
        if ($value === null) {
            return 'null';
        }
        if (!is_array($value)) {
            return var_export($value, true);
        }

        $items = array_map(
            fn ($key, $item) => (array_is_list($value) ? '' : var_export((string) $key, true) . ' => ') . $this->export($item),
            array_keys($value),
            $value
        );

        return '[' . implode(', ', $items) . ']';
    }

    private function listInCreateTables(string $migration): void
    {
        $file = base_path('create_tables.sql');
        $sql = file_get_contents($file);
        $sql = preg_replace("/(INSERT INTO `migrations` \(`migration`, `batch`\) VALUES\n(?:\('[^']+', 1\),\n)*\('[^']+', 1\));/", "\$1,\n('$migration', 1);", $sql, 1, $count);
        if ($count !== 1) {
            throw new RuntimeException('Could not find the migrations list in create_tables.sql');
        }
        file_put_contents($file, $sql);
    }
}
